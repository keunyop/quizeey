-- READ-ONLY operator inspection. Run only with a private read-only connection.
-- No secrets, CREATE/ALTER/INSERT/UPDATE/DELETE or generators. Output is not a full snapshot.
START TRANSACTION READ ONLY;
SELECT VERSION() AS server_version, DATABASE() AS source_database,
       @@character_set_database AS database_charset, @@collation_database AS database_collation,
       @@time_zone AS session_time_zone, @@system_time_zone AS system_time_zone;
SELECT TABLE_NAME,ENGINE,TABLE_COLLATION,TABLE_ROWS,DATA_LENGTH,INDEX_LENGTH
FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME;
SELECT TABLE_NAME,COLUMN_NAME,ORDINAL_POSITION,COLUMN_TYPE,IS_NULLABLE,COLUMN_DEFAULT,EXTRA,CHARACTER_SET_NAME,COLLATION_NAME
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,ORDINAL_POSITION;
SELECT TABLE_NAME,INDEX_NAME,NON_UNIQUE,SEQ_IN_INDEX,COLUMN_NAME
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,INDEX_NAME,SEQ_IN_INDEX;
SELECT TABLE_NAME,CONSTRAINT_NAME,COLUMN_NAME,REFERENCED_TABLE_NAME,REFERENCED_COLUMN_NAME
FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME,CONSTRAINT_NAME,ORDINAL_POSITION;
COMMIT;
-- TABLE_ROWS may be estimated. Exact counts, SHOW CREATE TABLE and snapshot/deltas must be collected separately.
